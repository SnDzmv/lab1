
#ifndef BOOK_H
#define BOOK_H

// Структура одной записи каталога книг.
struct Book {
    char title[30]; //название : до 29 символов и завершающий нулевой символ.
    char author[30]; // автор: до 29 символов и завершающий нулевой символ.
    int year; // Год выхода.
    int price; // Цена.
    char genre[20]; // жанр: до 19 символов и завершающий нулевой символ.
    char lang[10]; // язык: до 9 символов и завершающий нулевой символ.
};

#endif
